/**
 * markdown.serializer — HTML to clean markdown for AI consumption.
 *
 * Extends OmniPlug's seo-validator `htmlToText` / `parseDom`. We don't reuse
 * directly because we want markdown structure preserved, not flattened text.
 *
 * Uses jsdom (already a dep of OmniPlug seo-validator).
 *
 * @module llms-content/markdown.serializer
 */

import { JSDOM } from 'jsdom';

/**
 * Build llms.txt content for a tenant's sitemap.
 *
 * @param {object} opts
 * @param {string} opts.siteName
 * @param {string} opts.siteDomain
 * @param {string} opts.description
 * @param {Array}  opts.articles
 * @returns {string}
 */
export function buildSitemapMarkdown({ siteName, siteDomain, description, articles }) {
  let out = `# ${escapeMdInline(siteName)}\n\n`;

  if (description) {
    out += `> ${escapeMdInline(description)}\n\n`;
  }

  out += `Site URL: https://${siteDomain}\n\n`;
  out += `## Content\n\n`;

  for (const article of articles) {
    const title = escapeMdInline(article.title);
    const excerpt = excerptToOneLine(article.excerpt || article.title);
    const mdUrl = `https://${siteDomain}/wp-json/quoted/v1/llm/${article.slug}`;
    out += `- [${title}](${mdUrl}): ${excerpt}\n`;
  }

  out += `\n## About\n\n`;
  out += `This is the AI-readable sitemap for ${siteName}. `;
  out += `Each linked URL returns clean markdown for AI processing.\n\n`;
  out += `Generated by Quoted on ${new Date().toISOString().slice(0, 10)}.\n`;

  return out;
}

/**
 * Serialize a single article to markdown.
 *
 * @param {object} article — row from quoted_posts (passed in by the
 *   llms-content controller — tenant-scoped at the call site)
 * @param {object} opts
 * @returns {string}
 */
export function serializeArticleAsMarkdown(article, opts = {}) {
  const lines = [];

  // Title.
  lines.push(`# ${escapeMdInline(article.title)}`);
  lines.push('');

  // Frontmatter.
  if (article.author) lines.push(`Author: ${article.author}`);
  if (article.published_at) lines.push(`Published: ${formatDate(article.published_at)}`);
  if (article.modified_at && article.modified_at !== article.published_at) {
    lines.push(`Updated: ${formatDate(article.modified_at)}`);
  }
  if (article.canonical_url) lines.push(`Canonical: ${article.canonical_url}`);

  const categories = safeJsonParse(article.categories, []);
  if (categories.length > 0) {
    lines.push(`Categories: ${categories.join(', ')}`);
  }

  lines.push('');
  lines.push('---');
  lines.push('');

  // Body.
  const bodyMd = htmlToMarkdown(article.content_html || '');
  lines.push(bodyMd);

  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

/**
 * Convert an HTML string to markdown.
 * Walks the DOM, mapping elements to markdown constructs.
 */
export function htmlToMarkdown(html) {
  if (!html || typeof html !== 'string') return '';

  const dom = new JSDOM(`<!DOCTYPE html><html><body>${html}</body></html>`, {
    contentType: 'text/html',
  });
  const doc = dom.window.document;

  // Strip noise.
  const stripTags = ['script', 'style', 'iframe', 'nav', 'footer', 'aside', 'form', 'noscript', 'svg'];
  for (const tag of stripTags) {
    for (const el of Array.from(doc.querySelectorAll(tag))) {
      el.parentNode && el.parentNode.removeChild(el);
    }
  }

  return walk(doc.body).replace(/\n{3,}/g, '\n\n').trim();
}

// ─── DOM walker ────────────────────────────────────────────────────

function walk(node) {
  if (!node) return '';

  // Text node
  if (node.nodeType === 3) {
    return node.textContent;
  }

  // Element node
  if (node.nodeType !== 1) return '';

  const tag = node.tagName.toLowerCase();
  const inner = walkChildren(node);

  switch (tag) {
    case 'h1': return `\n# ${inner.trim()}\n\n`;
    case 'h2': return `\n## ${inner.trim()}\n\n`;
    case 'h3': return `\n### ${inner.trim()}\n\n`;
    case 'h4': return `\n#### ${inner.trim()}\n\n`;
    case 'h5': return `\n##### ${inner.trim()}\n\n`;
    case 'h6': return `\n###### ${inner.trim()}\n\n`;

    case 'p':
      return `\n${inner.trim()}\n\n`;

    case 'br':
      return '\n';

    case 'strong':
    case 'b':
      return `**${inner}**`;

    case 'em':
    case 'i':
      return `*${inner}*`;

    case 'code':
      // Inline code only here; <pre><code> handled below.
      return `\`${inner}\``;

    case 'pre': {
      const codeChild = Array.from(node.children).find(c => c.tagName === 'CODE');
      let lang = '';
      let codeText = inner;
      if (codeChild) {
        codeText = codeChild.textContent;
        const cls = codeChild.getAttribute('class') || '';
        const m = cls.match(/language-([a-z0-9]+)/i);
        if (m) lang = m[1];
      }
      return `\n\`\`\`${lang}\n${codeText}\n\`\`\`\n\n`;
    }

    case 'a': {
      const href = node.getAttribute('href') || '';
      if (!href) return inner;
      return `[${inner}](${href})`;
    }

    case 'img': {
      const src = node.getAttribute('src') || '';
      const alt = node.getAttribute('alt') || '';
      if (!src) return '';
      return `![${escapeMdInline(alt)}](${src})`;
    }

    case 'ul':
      return `\n${walkList(node, false)}\n`;

    case 'ol':
      return `\n${walkList(node, true)}\n`;

    case 'blockquote': {
      const trimmed = inner.trim();
      const lines = trimmed.split('\n').map(l => `> ${l}`);
      return `\n${lines.join('\n')}\n\n`;
    }

    case 'hr':
      return `\n---\n\n`;

    case 'table':
      return walkTable(node);

    // Pass-through containers
    case 'div':
    case 'section':
    case 'article':
    case 'main':
    case 'span':
    case 'figure':
    case 'figcaption':
    case 'body':
    case 'html':
      return inner;

    default:
      return inner;
  }
}

function walkChildren(node) {
  let out = '';
  for (const child of node.childNodes) {
    out += walk(child);
  }
  return out;
}

function walkList(node, ordered) {
  const items = [];
  let idx = 1;
  for (const child of node.childNodes) {
    if (child.nodeType === 1 && child.tagName.toLowerCase() === 'li') {
      const prefix = ordered ? `${idx++}. ` : '- ';
      let itemMd = walkChildren(child).trim();
      // Indent continuation lines.
      itemMd = itemMd.replace(/\n/g, '\n  ');
      items.push(prefix + itemMd);
    }
  }
  return items.join('\n');
}

function walkTable(node) {
  const rows = [];
  let headerDone = false;
  const trs = node.querySelectorAll('tr');

  for (const tr of trs) {
    const cells = [];
    let isHeader = false;
    for (const cell of tr.childNodes) {
      if (cell.nodeType !== 1) continue;
      const ctag = cell.tagName.toLowerCase();
      if (ctag === 'th') isHeader = true;
      if (ctag === 'th' || ctag === 'td') {
        cells.push(walkChildren(cell).trim().replace(/\s+/g, ' '));
      }
    }
    if (cells.length === 0) continue;
    rows.push(`| ${cells.join(' | ')} |`);
    if (isHeader && !headerDone) {
      rows.push(`|${' --- |'.repeat(cells.length)}`);
      headerDone = true;
    }
  }

  if (rows.length === 0) return '';
  return `\n${rows.join('\n')}\n\n`;
}

// ─── Helpers ────────────────────────────────────────────────────────

function escapeMdInline(str) {
  if (!str) return '';
  return String(str)
    .replace(/[\r\n]+/g, ' ')
    .replace(/\[/g, '\\[')
    .replace(/\]/g, '\\]')
    .trim();
}

function excerptToOneLine(str) {
  if (!str) return '';
  const flat = String(str)
    .replace(/<[^>]*>/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return flat.length > 200 ? flat.slice(0, 197) + '...' : flat;
}

function formatDate(iso) {
  try {
    return new Date(iso).toISOString().slice(0, 10);
  } catch {
    return iso;
  }
}

function safeJsonParse(str, fallback) {
  if (!str) return fallback;
  try {
    const v = JSON.parse(str);
    return Array.isArray(v) ? v : fallback;
  } catch {
    return fallback;
  }
}
